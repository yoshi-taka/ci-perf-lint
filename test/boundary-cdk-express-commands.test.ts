import { expect, test } from "bun:test";
import { textDeploysCdkWithoutExpress } from "../src/rules/shared/cdk-express.ts";

test.each([
  ["cdk deploy", true],
  ["cdk destroy", true],
  ["cdk bootstrap", true],
  ["cdk bootstrap --termination-protection", true],
  ["cdk bootstrap --termination-protection --express", false],
  ["aws-cdk deploy", true],
  ["./node_modules/.bin/cdk deploy", true],
  ["cdk.cmd deploy", true],
  ["env CI=true cdk deploy", true],
  ["CI=true npx cdk deploy", true],
  ["npx --yes cdk deploy", true],
  ["npx aws-cdk@2.1138.0 deploy", true],
  ["pnpm exec cdk deploy", true],
  ["pnpm dlx aws-cdk@2.1138.0 deploy", true],
  ["cdk deploy --express", false],
  ["cdk deploy --express=true", false],
  ["cdk deploy --express true", false],
  ["cdk deploy --express=false", true],
  ["cdk deploy --express false", true],
  ["cdk deploy --no-express", true],
  ["cdk deploy --express --no-express", true],
  ["cdk deploy --express=false --express", false],
  ["cdk deploy --express && cdk destroy", true],
  ["cdk deploy && cdk deploy --express", true],
  ["cdk deploy && echo --express", true],
  ["cdk deploy # --express", true],
  ['cdk deploy --app "node app.js --express"', true],
  ["cdk deploy --app --express", true],
  ['cdk deploy --context "notice=example --express"', true],
  ['cdk deploy --profile "development --express"', true],
  ["cdk deploy -- --express", true],
  ["cdk --profile dev deploy", true],
  ["cdk --express deploy", false],
  ["cdk deploy --method=direct --all --no-rollback", true],
  ["echo 'cdk deploy'", false],
  ["npm install aws-cdk", false],
  ["npm run deploy:dev", false],
  ["cdk synth --app 'cdk deploy'", false],
  ["cdk diff --context goal=deploy", false],
  ["cdk deploy --help", false],
  ["cdk deploy --version", false],
  ["cat <<EOF\ncdk deploy\nEOF", false],
  ["echo $(cdk deploy)", false],
  ["cdk deploy $OPTIONS", false],
  ["cdk deploy --express=$MODE", false],
  ["cdk deploy --express=maybe", false],
  ["cdk deploy --unknown value", false],
  ["if true; then cdk deploy; fi", false],
] as const)("CDK express mode belongs to the executable command: %s", (text, expected) => {
  expect(textDeploysCdkWithoutExpress(text)).toBe(expected);
});
