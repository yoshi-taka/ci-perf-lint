import { expect, test } from "bun:test";
import { textDeploysCdkWithoutMethodDirect } from "../src/rules/shared/cdk-express.ts";

test.each([
  ["cdk deploy", true],
  ["npx cdk deploy --express", true],
  ["cdk --profile sandbox deploy", true],
  ["cdk deploy --method=direct", false],
  ["cdk deploy --method direct", false],
  ["cdk deploy -m direct", false],
  ["cdk deploy -m=direct", false],
  ["cdk deploy -mdirect", false],
  ["cdk deploy --method=change-set", false],
  ["cdk deploy --method=prepare-change-set", false],
  ["cdk deploy --method=direct && cdk deploy", true],
  ["cdk deploy && cdk deploy --method=direct", true],
  ["cdk deploy && echo --method=direct", true],
  ["cdk deploy # --method=direct", true],
  ['cdk deploy --app "node app.js --method=direct"', true],
  ['cdk deploy --context "note=value -m direct"', true],
  ["cdk deploy -- --method=direct", true],
  ["cdk deploy --change-set-name review", false],
  ["cdk deploy --change-set-name=review", false],
  ['cdk deploy --app "node app.js --change-set-name review"', true],
  ["cdk deploy --import-existing-resources", false],
  ["cdk deploy --import-existing-resources=true", false],
  ["cdk deploy --import-existing-resources=false", true],
  ["cdk deploy --import-existing-resources false", true],
  ["cdk deploy --no-import-existing-resources", true],
  ["cdk deploy --import-existing-resources --no-import-existing-resources", true],
  ["cdk deploy --no-import-existing-resources --import-existing-resources", false],
  ["cdk deploy --revert-drift", false],
  ["cdk deploy --revert-drift=false", true],
  ["cdk deploy --revert-drift false", true],
  ["cdk deploy --no-revert-drift", true],
  ['cdk deploy --app "node app.js --revert-drift"', true],
  ["cdk deploy && echo --import-existing-resources", true],
  ["echo 'cdk deploy'", false],
  ["cdk synth --app 'cdk deploy'", false],
  ["cdk bootstrap", false],
  ["cdk destroy", false],
  ["cdk deploy --help", false],
  ["cdk deploy --method", false],
  ["cdk deploy --method=$METHOD", false],
  ["cat <<EOF\ncdk deploy\nEOF", false],
] as const)(
  "CDK method and change-set options belong to their invocation: %s",
  (text, expected) => {
    expect(textDeploysCdkWithoutMethodDirect(text)).toBe(expected);
  },
);
